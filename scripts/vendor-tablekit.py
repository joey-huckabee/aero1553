"""Vendor tablekit's CSV writer into third_party/tablekit, and check the copy is unchanged.

    python3 scripts/vendor-tablekit.py update CLONE TAG   # e.g. ../tablekit v0.7.0
    python3 scripts/vendor-tablekit.py check              # run by repo-hygiene and CI

aero1553 writes its CSV with tablekit-csv (L3-RS-002). tablekit is a private repository, so it
is vendored rather than fetched: every clone, CI run and offline bundle builds without a
credential for it, and an upgrade is a diff a reviewer reads. Only the two crates the CSV
writer needs are kept -- `tablekit` (the table model) and `tablekit-csv` -- with their
manifests and sources; tablekit's own workspace manifest is replaced by one trimmed to them.

`update` takes a local clone of tablekit (which needs access to it) and a tag, copies those
files as the tag has them, and writes `SHA256SUMS` naming the tag and its commit. `check`
needs nothing but this repository: every file under third_party/tablekit must be listed in
`SHA256SUMS` with its checksum, and every listed file must exist, so a local edit to the
vendored code fails the build. To change tablekit, change it upstream, tag it, and update.
"""

from __future__ import annotations

import hashlib
import io
import re
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "third_party" / "tablekit"
SUMS = DEST / "SHA256SUMS"
#: Files of ours in DEST, not tablekit's: not listed in SHA256SUMS.
OURS = {"SHA256SUMS", "VENDORED.md"}
#: What is copied from the tag, as `git archive` paths.
CRATES = [
    "crates/tablekit/Cargo.toml",
    "crates/tablekit/src",
    "crates/tablekit-csv/Cargo.toml",
    "crates/tablekit-csv/src",
]

WORKSPACE = """\
# Generated by scripts/vendor-tablekit.py from tablekit {tag}'s workspace manifest, trimmed
# to the two crates aero1553 vendors. Edit tablekit upstream, not this file.
[workspace]
resolver = "3"
members = ["crates/tablekit", "crates/tablekit-csv"]

[workspace.package]
{package}
[workspace.dependencies]
tablekit = {{ path = "crates/tablekit" }}
{dependencies}
[workspace.lints.rust]
{lints_rust}
[workspace.lints.clippy]
{lints_clippy}"""


def section(manifest: str, name: str) -> str:
    """The body of `[name]` in a TOML file: its lines up to the next table header."""
    match = re.search(rf"^\[{re.escape(name)}\]\n(.*?)(?=^\[|\Z)", manifest, re.M | re.S)
    if match is None:
        sys.exit(f"tablekit's workspace manifest has no [{name}]")
    return match.group(1)


def trimmed_workspace(manifest: str, tag: str) -> str:
    """tablekit's workspace manifest with only what the two vendored crates use."""
    deps = section(manifest, "workspace.dependencies")
    keep = [line for line in deps.splitlines() if re.match(r"^(zmij|itoa) = ", line)]
    if len(keep) != 2:
        sys.exit("tablekit's workspace manifest does not pin zmij and itoa as expected")
    return WORKSPACE.format(
        tag=tag,
        package=section(manifest, "workspace.package").rstrip() + "\n",
        dependencies="\n".join(keep) + "\n",
        lints_rust=section(manifest, "workspace.lints.rust").rstrip() + "\n",
        lints_clippy=section(manifest, "workspace.lints.clippy").rstrip() + "\n",
    )


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def vendored_files() -> list[str]:
    return sorted(
        p.relative_to(DEST).as_posix()
        for p in DEST.rglob("*")
        if p.is_file() and p.relative_to(DEST).as_posix() not in OURS
    )


def update(clone: Path, tag: str) -> int:
    git = ["git", "-C", str(clone)]
    commit = subprocess.run(
        [*git, "rev-parse", f"{tag}^{{commit}}"], check=True, capture_output=True, text=True
    ).stdout.strip()
    archive = subprocess.run(
        [*git, "archive", "--format=tar", tag, *CRATES], check=True, capture_output=True
    ).stdout
    manifest = subprocess.run(
        [*git, "show", f"{tag}:Cargo.toml"], check=True, capture_output=True, text=True
    ).stdout
    for path in vendored_files():
        (DEST / path).unlink()
    for directory in sorted((p for p in DEST.rglob("*") if p.is_dir()), reverse=True):
        if not any(directory.iterdir()):
            directory.rmdir()
    DEST.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            if member.isfile():
                target = DEST / member.name
                target.parent.mkdir(parents=True, exist_ok=True)
                source = tar.extractfile(member)
                assert source is not None
                target.write_bytes(source.read())
    (DEST / "Cargo.toml").write_text(trimmed_workspace(manifest, tag), encoding="utf-8")
    lines = [f"# tablekit {tag} (commit {commit}), vendored by scripts/vendor-tablekit.py"]
    lines += [f"{digest(DEST / path)}  {path}" for path in vendored_files()]
    SUMS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"vendored tablekit {tag} ({commit[:12]}): {len(lines) - 1} files")
    return 0


def check() -> int:
    if not SUMS.exists():
        print(f"vendor-tablekit: {SUMS.relative_to(ROOT)} is missing", file=sys.stderr)
        return 1
    listed: dict[str, str] = {}
    for line in SUMS.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            want, path = line.split("  ", 1)
            listed[path] = want
    problems = [
        f"changed: {p}"
        for p, want in listed.items()
        if (DEST / p).is_file() and digest(DEST / p) != want
    ]
    problems += [f"missing: {p}" for p in listed if not (DEST / p).is_file()]
    problems += [f"not vendored from tablekit: {p}" for p in vendored_files() if p not in listed]
    if problems:
        print(
            "vendor-tablekit: third_party/tablekit differs from the tag it names:",
            *problems,
            "Change tablekit upstream, tag it, and run `update`.",
            sep="\n  ",
            file=sys.stderr,
        )
        return 1
    header = SUMS.read_text(encoding="utf-8").splitlines()[0]
    print(f"vendor-tablekit: {len(listed)} files match ({header.lstrip('# ')})")
    return 0


def main() -> int:
    args = sys.argv[1:]
    if args == ["check"]:
        return check()
    if len(args) == 3 and args[0] == "update":
        return update(Path(args[1]), args[2])
    print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
